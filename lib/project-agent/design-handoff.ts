import type { ProjectAgentTaskFile } from "./types";

export interface DesignHandoff {
  id: string;
  source: ProjectAgentTaskFile;
  pdf: ProjectAgentTaskFile;
  dxf: ProjectAgentTaskFile;
  glb: ProjectAgentTaskFile;
  preview?: ProjectAgentTaskFile;
  viewer?: ProjectAgentTaskFile;
  ifc?: ProjectAgentTaskFile;
  files: ProjectAgentTaskFile[];
}

const DESIGN_NAME = /^(design-[a-f0-9]{12})\.(design\.json|preview\.png|web\.html|pdf|dxf|glb|ifc)$/;

/** Groups only a complete authored design set; partial or unrelated files keep their normal download cards. */
export function collectDesignHandoffs(files: ProjectAgentTaskFile[]): {
  handoffs: DesignHandoff[];
  groupedIds: Set<string>;
} {
  const candidates = new Map<string, Map<string, ProjectAgentTaskFile>>();
  for (const file of files) {
    const found = DESIGN_NAME.exec(file.name);
    if (!found) continue;
    const group = candidates.get(found[1]) ?? new Map<string, ProjectAgentTaskFile>();
    if (!group.has(found[2])) group.set(found[2], file);
    candidates.set(found[1], group);
  }
  const handoffs: DesignHandoff[] = [], groupedIds = new Set<string>();
  for (const [id, group] of candidates) {
    const source = group.get("design.json"), pdf = group.get("pdf");
    const dxf = group.get("dxf"), glb = group.get("glb");
    if (!source || !pdf || !dxf || !glb) continue;
    const groupedFiles = [...group.values()];
    handoffs.push({
      id, source, pdf, dxf, glb, files: groupedFiles,
      preview: group.get("preview.png"),
      viewer: group.get("web.html"),
      ifc: group.get("ifc"),
    });
    for (const file of groupedFiles) groupedIds.add(file.id);
  }
  return { handoffs, groupedIds };
}

/** The input path is restricted to a file name generated by the design engine. */
export function makeDesignEditPrompt(sourceName: string): string | null {
  if (!/^design-[a-f0-9]{12}\.design\.json$/.test(sourceName)) return null;
  return "Edit the EXISTING interior design using the design_edit action. " +
    'Source: "outputs/' + sourceName + '". ' +
    "Keep the previous version unchanged and export updated PDF, DXF, GLB and IFC if available. " +
    "Requested changes: ";
}
